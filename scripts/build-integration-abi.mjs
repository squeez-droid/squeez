#!/usr/bin/env node
// Builds the public integration ABI (events + execution functions) straight from the compiled contracts.
//
//   node scripts/build-integration-abi.mjs          write apps/web/public/squeez-integration-abi.json
//   node scripts/build-integration-abi.mjs --check  fail if the committed file is out of date
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { toEventSelector, toFunctionSelector } from "viem";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = resolve(root, "packages/contracts");
const output = resolve(root, "apps/web/public/squeez-integration-abi.json");

const inspect = (target) => JSON.parse(execFileSync(
  "forge", ["inspect", "--offline", target, "abi", "--json"], { cwd: contracts, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
));
const pick = (abi, type, names) => names.map((name) => {
  const item = abi.find((entry) => entry.type === type && entry.name === name);
  if (!item) throw new Error(`${type} ${name} not found in compiled ABI`);
  return item;
});
const signature = (item) => `${item.name}(${item.inputs.map(function type(input) {
  return input.type.startsWith("tuple") ? `(${input.components.map(type).join(",")})${input.type.slice(5)}` : input.type;
}).join(",")})`;

const squeezEvents = inspect("src/interfaces/ISqueezEvents.sol:ISqueezEvents");
const hook = inspect("src/SqueezHook.sol:SqueezHook");
const locker = inspect("src/SqueezLiquidityLocker.sol:SqueezLiquidityLocker");
const vault = inspect("src/SqueezFeeVault.sol:SqueezFeeVault");
const curve = inspect("src/SqueezCurve.sol:SqueezCurve");
const poolManager = inspect("../../node_modules/@uniswap/v4-core/src/interfaces/IPoolManager.sol:IPoolManager");

// `SqueezBurned` is declared in ISqueezEvents but no deployed contract emits it, so it is not published.
const events = [
  ...pick(squeezEvents, "event", [
    "TokenLaunched", "TokenMetadata", "ProtectionPolicyPinned", "CreatorAttested",
    "CurveTrade", "ProtectedPurchaseRecorded", "GraduationThresholdReached", "GraduationAttempted", "Graduated",
    "PoolSwap", "CreatorFeeAccrued", "ProtectionTaxAccrued", "CreatorFeeClaimed", "FeeRecipientUpdated",
  ]).map((item) => ({ item, emittedBy: ({
    TokenLaunched: "factory", TokenMetadata: "factory", ProtectionPolicyPinned: "factory", CreatorAttested: "factory",
    PoolSwap: "swapRouter", CreatorFeeAccrued: "feeVault", ProtectionTaxAccrued: "feeVault", CreatorFeeClaimed: "feeVault",
  })[item.name] ?? "curve" })),
  ...pick(vault, "event", ["ProtocolFeeAccrued"]).map((item) => ({ item, emittedBy: "feeVault" })),
  ...pick(hook, "event", ["SqueezPoolRegistered"]).map((item) => ({ item, emittedBy: "hook" })),
  ...pick(locker, "event", ["PositionLocked"]).map((item) => ({ item, emittedBy: "liquidityLocker" })),
  ...pick(poolManager, "event", ["Initialize", "Swap"]).map((item) => ({ item, emittedBy: "poolManager" })),
];
const functions = pick(curve, "function", [
  "quoteBuy", "quoteSell", "buy", "sell", "buyTo", "sellTo", "graduate", "sniperTaxBps", "graduated", "config",
  "hypeRaised", "token", "creator", "creatorFeeBps", "launchedAt", "launchedAtBlock", "protectionPolicyId",
  "protectionWindowSeconds", "maxBuyBpsPerTransaction", "maxBuyBpsPerAddress", "purchasedDuringProtection",
  "graduationPool",
]);

const document = {
  schema: "squeez.integration-abi.v1",
  note: "Generated by scripts/build-integration-abi.mjs from the compiled contracts. `hypeAmount`/`hypeRaised` fields hold the chain's native currency (ETH on Robinhood Chain).",
  chains: {
    robinhood: {
      chainId: 4663,
      emitters: {
        factory: "0x7fd8F81f27d010f6550bA92203c1D5322Dd7B30E",
        feeVault: "0xDd3d50eb4d35ba86Ca94fd5c0A2333e2632d7551",
        hook: "0x27468dCA279b568a56C4EAF594Af94B887Aca0CC",
        swapRouter: "0xBd3536eF5bFe791E4419c1A2A14C4D8F325c15b4",
        liquidityLocker: "0x5E81206e42E82e24B1e07167c2007b89D8D3E55f",
        poolManager: "0x8366a39CC670B4001A1121B8F6A443A643e40951",
        curve: "per token: see the TokenLaunched event (topic 2) or the factory's launches",
      },
      factoryStartBlock: 110951498,
    },
  },
  events: events.map(({ item, emittedBy }) => ({ name: item.name, emittedBy, topic0: toEventSelector(item), abi: item })),
  curveFunctions: functions.map((item) => ({ name: item.name, selector: toFunctionSelector(signature(item)), abi: item })),
  abi: [...events.map(({ item }) => item), ...functions],
};
const text = `${JSON.stringify(document, null, 2)}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text) throw new Error("squeez-integration-abi.json is out of date; run the generator");
  console.log("squeez-integration-abi.json is up to date");
} else {
  writeFileSync(output, text);
  console.log(`wrote ${output}: ${document.events.length} events, ${document.curveFunctions.length} functions`);
}
